"""Make the ``aletta-2024@1`` angle set from the SATP circumplex validation output.

Reads ``outputs/2024-06-13/sem-fit-ipsatized.csv`` of ``MitchellAcoustics/SATP-circumplex-
validation`` at the pinned commit, from ``--source PATH`` or downloaded from GitHub, refuses
it unless its sha256 is the pinned one, and writes ``aletta-2024/1.toml`` into
``src/soundscapy/_data/angle_sets/`` (or ``--out DIR``).

The angles come from the ``Equal comm.`` rows of the languages that pass the paper's fit
rule (CFI >= 0.92, GFI >= 0.90, SRMR < 0.08; Aletta et al. 2024, Table 2, p. 10); a
language is reflected (theta -> (360 - theta) mod 360) when its raw PAQ2 angle exceeds its
raw PAQ3 angle, so vibrant precedes eventful as in the paper's Table 4 (p. 12). The six
languages without angles get their tier from a transcription of Table 2 by the paper's
stated rule (Table 4's caption): Low did not pass Step 1 (CI > 0.7), Medium passed Step 1
but not Step 2 (the fit rule), High the rest. The script asserts that the rule applied to
the CSV selects the twelve High languages of the transcription. Running it twice gives
identical bytes. Run with ``uv run scripts/make_aletta_2024.py``.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import io
import itertools
import sys
import urllib.request
from pathlib import Path

import tomlkit

SOURCE_REPO = "MitchellAcoustics/SATP-circumplex-validation"
SOURCE_COMMIT = "3509da3e9191586430582e42f5f86945aa4965c5"
SOURCE_PATH = "outputs/2024-06-13/sem-fit-ipsatized.csv"
SOURCE_URL = f"https://raw.githubusercontent.com/{SOURCE_REPO}/{SOURCE_COMMIT}/{SOURCE_PATH}"
SOURCE_SHA256 = "d3ad6da994013082090c27e4592ae5bcdf267a91e5e5fe2c7eb5804eef25df05"
OUT_DIR = Path(__file__).resolve().parents[1] / "src/soundscapy/_data/angle_sets"
OUT_NAME = "aletta-2024/1.toml"
MODEL_TYPE = "Equal comm."
POSITIONS = tuple(f"PAQ{i}" for i in range(1, 9))
FULL_TURN_DEG = 360.0

# Step 2 fit thresholds (Table 2, p. 10). CFI is applied as >= 0.92 because the paper
# carries spa (CFI 0.920) to Step 3.
CFI_MIN = 0.92
GFI_MIN = 0.90
SRMR_MAX = 0.08
# Step 1 threshold: the correspondence index must exceed 0.7.
CI_MIN = 0.7

# Table 2 (p. 10) of Aletta et al. (2024): Step 1 correspondence index, then the Step 2 fit
# of the equal-communality model (CFI, GFI, SRMR), None where the paper ran no Step 2.
TABLE_2: dict[str, tuple[float, tuple[float, float, float] | None]] = {
    "arb": (0.889, (0.971, 0.969, 0.044)),
    "cmn": (0.819, (0.960, 0.954, 0.044)),
    "deu": (0.972, (0.943, 0.915, 0.059)),
    "ell": (0.910, (0.928, 0.934, 0.079)),
    "eng": (0.986, (0.934, 0.907, 0.052)),
    "fra": (0.931, (0.919, 0.913, 0.098)),
    "hrv": (0.861, (0.949, 0.926, 0.065)),
    "ind": (0.771, (0.933, 0.923, 0.078)),
    "ita": (0.910, (0.944, 0.932, 0.069)),
    "jpn": (0.833, (0.892, 0.896, 0.087)),
    "kor": (0.819, (0.952, 0.941, 0.084)),
    "nld": (0.812, (0.967, 0.943, 0.056)),
    "por": (0.764, (0.925, 0.917, 0.092)),
    "spa": (0.965, (0.920, 0.910, 0.063)),
    "swe": (0.972, (0.944, 0.924, 0.053)),
    "tur": (0.812, (0.927, 0.915, 0.079)),
    "vie": (0.694, None),
    "zsm": (0.674, None),
}

# Where Table 4 (p. 12) prints another tier than the stated rule gives, or where the rule
# needs stating, the entry's note says so.
NOTES = {
    "fra": "Passed Step 1 (CI 0.931) but not Step 2 (Table 2, p. 10); no adjusted angles.",
    "por": "Passed Step 1 (CI 0.764) but not Step 2 (Table 2, p. 10); no adjusted angles.",
    "jpn": (
        "Passed Step 1 (CI 0.833) but not Step 2 (CFI 0.892, GFI 0.896, SRMR 0.087; Table 2, "
        "p. 10), so Medium by the paper's stated rule; Table 4 (p. 12) prints Low. No adjusted "
        "angles."
    ),
    "kor": (
        "Passed Step 1 (CI 0.819) but not Step 2 (SRMR 0.084; Table 2, p. 10), so Medium by "
        "the paper's stated rule; Table 4 (p. 12) prints High with angles 0, 56, 90, 124, 151, "
        "251, 275, 288, which are not shipped."
    ),
    "vie": "Did not pass Step 1 (CI 0.694; Table 2, p. 10); no adjusted angles.",
    "zsm": "Did not pass Step 1 (CI 0.674; Table 2, p. 10); no adjusted angles.",
}

CITATION = {
    "citation": (
        "Aletta, F., Mitchell, A., Oberman, T., Kang, J., et al. (2024). Soundscape descriptors "
        "in eighteen languages: Translation and validation through listening experiments. "
        "Applied Acoustics 224, 110109."
    ),
    "doi_or_url": "https://doi.org/10.1016/j.apacoust.2024.110109",
    "licence": (
        "CC-BY-4.0 (the paper); BSD-3-Clause (the source repository "
        "MitchellAcoustics/SATP-circumplex-validation)"
    ),
    "date": "2024",
    "notes": (
        "Angles: Table 4, p. 12, generated by scripts/make_aletta_2024.py from "
        f"SATP-circumplex-validation@{SOURCE_COMMIT[:7]} {SOURCE_PATH} ('Equal comm.' rows of "
        "the languages passing CFI >= 0.92, GFI >= 0.90, SRMR < 0.08; reflected when the raw "
        "PAQ2 angle exceeds the raw PAQ3 angle). Tiers: Table 4's caption applied to Table 2, "
        "p. 10 (Low: CI <= 0.7; Medium: not passing Step 2; High: the rest); jpn and kor are "
        "Medium by that rule where Table 4 prints Low and High, see their notes."
    ),
}


def passes_fit(cfi: float, gfi: float, srmr: float) -> bool:
    """Apply the paper's Step 2 fit rule."""
    return cfi >= CFI_MIN and gfi >= GFI_MIN and srmr < SRMR_MAX


def tier_from_table_2(ci: float, fit: tuple[float, float, float] | None) -> str:
    """Apply Table 4's caption to a Table 2 row."""
    if ci <= CI_MIN or fit is None:
        return "low"
    return "high" if passes_fit(*fit) else "medium"


def angles_from_csv(source: bytes) -> dict[str, list[float]]:
    """Return the adjusted angles of every language whose ``Equal comm.`` row passes the rule."""
    reader = csv.DictReader(io.StringIO(source.decode("utf-8"), newline=""))
    angles: dict[str, list[float]] = {}
    for row in reader:
        if row["Model Type"] != MODEL_TYPE:
            continue
        if not passes_fit(float(row["CFI"]), float(row["GFI"]), float(row["SRMR"])):
            continue
        raw = [float(row[p]) for p in POSITIONS]
        if raw[1] > raw[2]:  # vibrant after eventful: the fit ran the circle the other way
            raw = [(FULL_TURN_DEG - a) % FULL_TURN_DEG for a in raw]
        angles[row["Language"]] = raw
    return angles


def check_against_table_2(angles: dict[str, list[float]]) -> None:
    """Exit unless the CSV's passing languages are Table 2's High languages."""
    expected = {code for code, (ci, fit) in TABLE_2.items() if tier_from_table_2(ci, fit) == "high"}
    if set(angles) != expected:
        sys.exit(f"the fit rule selected {sorted(angles)}, Table 2 gives {sorted(expected)}")
    if len(angles) != 12:  # noqa: PLR2004  # the paper's count of High languages
        sys.exit(f"expected 12 High languages, got {len(angles)}")
    for code, values in angles.items():
        if values[0] != 0.0 or any(b <= a for a, b in itertools.pairwise(values)):
            sys.exit(f"{code}: angles are not strictly increasing from 0: {values}")


def angle_set_toml(angles: dict[str, list[float]]) -> str:
    """Return the angle set as TOML text."""
    doc = tomlkit.document()
    doc["schema"] = "soundscapy.angle_set"
    doc["schema_version"] = 1
    doc["name"] = "aletta-2024"
    doc["version"] = "1"
    doc["circumplex"] = "iso-12913-outdoor"
    doc["circumplex_version"] = "1"
    citation = tomlkit.table()
    citation.update(CITATION)
    doc["citation"] = citation
    languages = tomlkit.table(is_super_table=True)
    for code in sorted(TABLE_2):
        entry = tomlkit.table()
        if code in angles:
            entry["tier"] = "high"
            entry["angles_deg"] = angles[code]
        else:
            ci, fit = TABLE_2[code]
            entry["tier"] = tier_from_table_2(ci, fit)
            entry["note"] = NOTES[code]
        languages[code] = entry
    doc["languages"] = languages
    return tomlkit.dumps(doc)


def _download() -> bytes:
    with urllib.request.urlopen(
        SOURCE_URL, timeout=120
    ) as response:  # fixed https URL at a pinned commit
        return response.read()


def main() -> None:
    """Check the source, then write the angle set."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--source", type=Path, help=f"a local copy of {SOURCE_PATH!r}")
    parser.add_argument("--out", type=Path, default=OUT_DIR, help="the angle_sets directory")
    args = parser.parse_args()
    source = args.source.read_bytes() if args.source else _download()
    digest = hashlib.sha256(source).hexdigest()
    if digest != SOURCE_SHA256:
        where = args.source or SOURCE_URL
        sys.exit(f"refusing {where}: sha256 {digest}, expected {SOURCE_SHA256}")
    angles = angles_from_csv(source)
    check_against_table_2(angles)
    out = args.out / OUT_NAME
    out.parent.mkdir(parents=True, exist_ok=True)
    data = angle_set_toml(angles).encode("utf-8")
    out.write_bytes(data)
    print(f"wrote {out} ({len(data)} bytes); {len(angles)} languages with angles")


if __name__ == "__main__":
    main()
